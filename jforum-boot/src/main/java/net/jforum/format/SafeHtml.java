package net.jforum.format;

import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

/**
 * Port of legacy net.jforum.util.SafeHtml. Works at token level (like the htmlparser Lexer used by
 * JForum 2.1.8) so the output keeps the original markup layout: non-welcome tags are escaped, unwanted
 * or unsafe attributes (on*, javascript: links, style with "(") are dropped.
 */
public class SafeHtml {

    private static final Pattern TAG = Pattern.compile(
        "<(/?)([A-Za-z][A-Za-z0-9:-]*+)((?:\\s++|[^\\s=>/\"']++(?:\\s*+=\\s*+(?:\"[^\"]*+\"|'[^']*+'|[^\\s>\"']*+))?|\"[^\"]*+\"|'[^']*+'|/)*+)>");
    private static final Pattern ATTR_TOKEN = Pattern.compile(
        "(\\s++)|([^\\s=>/\"']++)(?:\\s*+=\\s*+(\"[^\"]*+\"|'[^']*+'|[^\\s>\"']*+))?|(\"[^\"]*+\"|'[^']*+')|(/)");

    /** Smilie images generated by the formatter itself are always allowed. */
    static final String SMILIES_PATH = "/images/smilies/";

    private final Set<String> welcomeTags;
    private final Set<String> welcomeAttributes;
    private final List<String> allowedProtocols;
    private final boolean allowRelativeLinks;

    public SafeHtml(String welcomeTags, String welcomeAttributes, String allowedProtocols, boolean allowRelativeLinks) {
        this.welcomeTags = split(welcomeTags, false);
        this.welcomeAttributes = split(welcomeAttributes, true);
        this.allowedProtocols = split(allowedProtocols, false).stream().toList();
        this.allowRelativeLinks = allowRelativeLinks;
    }

    private static Set<String> split(String csv, boolean upper) {
        if (csv == null) {
            return Set.of();
        }
        return Arrays.stream(csv.split(","))
            .map(String::trim)
            .filter(s -> !s.isEmpty())
            .map(s -> upper ? s.toUpperCase(Locale.ROOT) : s.toLowerCase(Locale.ROOT))
            .collect(Collectors.toCollection(java.util.LinkedHashSet::new));
    }

    /** Escapes every tag not in the welcome list and strips unwanted attributes from the others. */
    public String makeSafe(String contents) {
        if (contents == null || contents.isEmpty()) {
            return contents;
        }
        StringBuilder sb = new StringBuilder(contents.length());
        Matcher m = TAG.matcher(contents);
        int pos = 0;
        while (pos < contents.length()) {
            int lt = contents.indexOf('<', pos);
            while (lt > -1 && !m.region(lt, contents.length()).lookingAt()) {
                lt = contents.indexOf('<', lt + 1);
            }
            if (lt < 0) {
                appendText(sb, contents.substring(pos));
                break;
            }
            appendText(sb, contents.substring(pos, lt));
            String tagName = m.group(2).toLowerCase(Locale.ROOT);
            if (welcomeTags.contains(tagName)) {
                sb.append(rebuild(m, true));
            } else {
                sb.append(m.group().replace("<", "&lt;").replace(">", "&gt;"));
            }
            pos = m.end();
        }
        return sb.toString();
    }

    /** Removes unsafe attributes from every tag, without checking the welcome lists. */
    public String ensureAllAttributesAreSafe(String contents) {
        if (contents == null || contents.isEmpty()) {
            return contents;
        }
        StringBuilder sb = new StringBuilder(contents.length());
        Matcher m = TAG.matcher(contents);
        int pos = 0;
        while (m.find(pos)) {
            sb.append(contents, pos, m.start()).append(rebuild(m, false));
            pos = m.end();
        }
        sb.append(contents.substring(pos));
        return sb.toString();
    }

    private static void appendText(StringBuilder sb, String text) {
        if (text.indexOf('<') > -1 || text.indexOf('>') > -1) {
            sb.append(text.replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;"));
        } else {
            sb.append(text);
        }
    }

    private String rebuild(Matcher tag, boolean checkWelcome) {
        StringBuilder sb = new StringBuilder("<").append(tag.group(1)).append(tag.group(2));
        Matcher a = ATTR_TOKEN.matcher(tag.group(3));
        while (a.find()) {
            if (a.group(1) != null || a.group(4) != null || a.group(5) != null) {
                sb.append(a.group());
                continue;
            }
            String name = a.group(2).toUpperCase(Locale.ROOT);
            String rawValue = a.group(3);
            if (rawValue == null) {
                sb.append(a.group());
                continue;
            }
            String value = unquote(rawValue);
            if (checkWelcome && !welcomeAttributes.contains(name)) {
                continue;
            }
            if (!isAttributeSafe(name, value.toLowerCase(Locale.ROOT))) {
                continue;
            }
            sb.append(a.group().replace("&#", "&amp;#"));
        }
        return sb.append('>').toString();
    }

    private static String unquote(String v) {
        if (v.length() >= 2 && (v.charAt(0) == '"' || v.charAt(0) == '\'') && v.charAt(v.length() - 1) == v.charAt(0)) {
            return v.substring(1, v.length() - 1);
        }
        return v;
    }

    private boolean isAttributeSafe(String name, String value) {
        if (name.startsWith("ON")) {
            return false;
        }
        if (value.indexOf('\n') > -1 || value.indexOf('\r') > -1 || value.indexOf('\0') > -1) {
            return false;
        }
        if ("HREF".equals(name) || "SRC".equals(name)) {
            return isHrefValid(value);
        }
        if ("STYLE".equals(name)) {
            return value.indexOf('(') < 0;
        }
        return true;
    }

    private boolean isHrefValid(String href) {
        if (href.startsWith(SMILIES_PATH) && !href.contains("..")) {
            return true;
        }
        if (allowRelativeLinks && href.startsWith("/") && !href.startsWith("//")) {
            return true;
        }
        return allowedProtocols.stream().anyMatch(href::startsWith);
    }
}
